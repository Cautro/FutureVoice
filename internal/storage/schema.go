package storage

import (
	"context"
	"fmt"
)

func (s *Storage) initSchema(ctx context.Context) error {
	tx, err := s.DB.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin schema transaction: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	statements := []string{
		`CREATE TABLE IF NOT EXISTS users (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			telegram_id BIGINT,
			role TEXT NOT NULL DEFAULT 'student',
			username TEXT NOT NULL DEFAULT '',
			first_name TEXT NOT NULL DEFAULT '',
			last_name TEXT NOT NULL DEFAULT '',
			is_active BOOLEAN NOT NULL DEFAULT TRUE,
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
			updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		)`,
		`ALTER TABLE users ADD COLUMN IF NOT EXISTS telegram_id BIGINT`,
		`ALTER TABLE users ADD COLUMN IF NOT EXISTS username TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE users ADD COLUMN IF NOT EXISTS first_name TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE users ADD COLUMN IF NOT EXISTS last_name TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE users ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE`,
		`ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()`,
		`ALTER TABLE users ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()`,
		`DO $$
		BEGIN
			IF EXISTS (
				SELECT 1 FROM information_schema.columns
				WHERE table_schema = current_schema() AND table_name = 'users'
				  AND column_name = 'telegram_id' AND data_type <> 'bigint'
			) THEN
				ALTER TABLE users ALTER COLUMN telegram_id TYPE BIGINT USING telegram_id::BIGINT;
			END IF;
		END $$`,
		`ALTER TABLE users ALTER COLUMN role SET DEFAULT 'student'`,
		`UPDATE users SET role = 'student' WHERE role = 'user'`,
		`CREATE UNIQUE INDEX IF NOT EXISTS users_telegram_id_uidx ON users (telegram_id)`,

		`CREATE TABLE IF NOT EXISTS requests (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			user_id BIGINT NOT NULL REFERENCES users(id),
			request_type TEXT NOT NULL,
			theme TEXT NOT NULL,
			description TEXT NOT NULL,
			status TEXT NOT NULL DEFAULT 'open',
			source_key TEXT,
			assigned_to BIGINT REFERENCES users(id),
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
			updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
			deleted_at TIMESTAMPTZ,
			deleted_by_user_id BIGINT REFERENCES users(id),
			CONSTRAINT requests_type_check CHECK (request_type IN ('complaint', 'offer', '3dPrintOffer')),
			CONSTRAINT requests_status_check CHECK (status IN ('open', 'in_progress', 'waiting_for_user', 'closed', 'rejected'))
		)`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS user_id BIGINT`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS request_type TEXT NOT NULL DEFAULT 'complaint'`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS theme TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'open'`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS source_key TEXT`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS assigned_to BIGINT`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ`,
		`ALTER TABLE requests ADD COLUMN IF NOT EXISTS deleted_by_user_id BIGINT`,
		`DO $$
		DECLARE sequence_name TEXT;
		BEGIN
			IF EXISTS (
				SELECT 1 FROM information_schema.columns
				WHERE table_schema = current_schema() AND table_name = 'requests'
				  AND column_name = 'id' AND data_type <> 'bigint'
			) THEN
				ALTER TABLE requests ALTER COLUMN id TYPE BIGINT USING id::BIGINT;
			END IF;
			sequence_name := pg_get_serial_sequence('requests', 'id');
			IF sequence_name IS NOT NULL THEN
				EXECUTE format('ALTER SEQUENCE %s AS BIGINT', sequence_name::regclass);
			END IF;
			IF EXISTS (
				SELECT 1 FROM information_schema.columns
				WHERE table_schema = current_schema() AND table_name = 'requests'
				  AND column_name = 'user_id' AND data_type <> 'bigint'
			) THEN
				ALTER TABLE requests ALTER COLUMN user_id TYPE BIGINT USING user_id::BIGINT;
			END IF;
		END $$`,
		`DO $$
		DECLARE old_column TEXT;
		BEGIN
			FOREACH old_column IN ARRAY ARRAY['userid', 'userId'] LOOP
				IF EXISTS (
					SELECT 1 FROM information_schema.columns
					WHERE table_schema = current_schema() AND table_name = 'requests' AND column_name = old_column
				) THEN
					EXECUTE format('UPDATE requests SET user_id = %I WHERE user_id IS NULL', old_column);
					EXIT;
				END IF;
			END LOOP;
			FOREACH old_column IN ARRAY ARRAY['requesttype', 'requestType'] LOOP
				IF EXISTS (
					SELECT 1 FROM information_schema.columns
					WHERE table_schema = current_schema() AND table_name = 'requests' AND column_name = old_column
				) THEN
					EXECUTE format('UPDATE requests SET request_type = %I WHERE request_type = ''complaint''', old_column);
					EXIT;
				END IF;
			END LOOP;
		END $$`,
		`UPDATE requests SET request_type = 'complaint' WHERE request_type IS NULL OR request_type = ''`,
		`UPDATE requests SET theme = '' WHERE theme IS NULL`,
		`UPDATE requests SET description = '' WHERE description IS NULL`,
		`UPDATE requests SET status = 'open' WHERE status IS NULL OR status = ''`,
		`UPDATE requests SET created_at = NOW() WHERE created_at IS NULL`,
		`UPDATE requests SET updated_at = created_at WHERE updated_at IS NULL`,
		`DO $$
		BEGIN
			IF EXISTS (SELECT 1 FROM requests WHERE user_id IS NULL) THEN
				RAISE EXCEPTION 'requests.user_id contains NULL values after legacy migration';
			END IF;
			ALTER TABLE requests ALTER COLUMN user_id SET NOT NULL;
			ALTER TABLE requests ALTER COLUMN request_type SET NOT NULL;
			ALTER TABLE requests ALTER COLUMN theme SET NOT NULL;
			ALTER TABLE requests ALTER COLUMN description SET NOT NULL;
			ALTER TABLE requests ALTER COLUMN status SET NOT NULL;
			ALTER TABLE requests ALTER COLUMN created_at SET NOT NULL;
			ALTER TABLE requests ALTER COLUMN updated_at SET NOT NULL;
		END $$`,
		`DO $$
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM pg_constraint
				WHERE conname = 'requests_user_id_fkey' AND conrelid = 'requests'::regclass
			) THEN
				ALTER TABLE requests ADD CONSTRAINT requests_user_id_fkey
				FOREIGN KEY (user_id) REFERENCES users(id) NOT VALID;
			END IF;
			IF NOT EXISTS (
				SELECT 1 FROM pg_constraint
				WHERE conname = 'requests_deleted_by_user_id_fkey' AND conrelid = 'requests'::regclass
			) THEN
				ALTER TABLE requests ADD CONSTRAINT requests_deleted_by_user_id_fkey
				FOREIGN KEY (deleted_by_user_id) REFERENCES users(id) NOT VALID;
			END IF;
			IF NOT EXISTS (
				SELECT 1 FROM pg_constraint
				WHERE conname = 'requests_type_check' AND conrelid = 'requests'::regclass
			) THEN
				ALTER TABLE requests ADD CONSTRAINT requests_type_check
				CHECK (request_type IN ('complaint', 'offer', '3dPrintOffer')) NOT VALID;
			END IF;
			-- Recreate the status constraint to migrate databases created before
			-- waiting_for_user and rejected statuses were introduced.
			ALTER TABLE requests DROP CONSTRAINT IF EXISTS requests_status_check;
			ALTER TABLE requests ADD CONSTRAINT requests_status_check
			CHECK (status IN ('open', 'in_progress', 'waiting_for_user', 'closed', 'rejected')) NOT VALID;
			IF NOT EXISTS (
				SELECT 1 FROM pg_constraint
				WHERE conname = 'requests_assigned_to_fkey' AND conrelid = 'requests'::regclass
			) THEN
				ALTER TABLE requests ADD CONSTRAINT requests_assigned_to_fkey
				FOREIGN KEY (assigned_to) REFERENCES users(id) NOT VALID;
			END IF;
		END $$`,
		`ALTER TABLE requests VALIDATE CONSTRAINT requests_user_id_fkey`,
		`ALTER TABLE requests VALIDATE CONSTRAINT requests_deleted_by_user_id_fkey`,
		`ALTER TABLE requests VALIDATE CONSTRAINT requests_type_check`,
		`ALTER TABLE requests VALIDATE CONSTRAINT requests_status_check`,
		`ALTER TABLE requests VALIDATE CONSTRAINT requests_assigned_to_fkey`,
		`CREATE UNIQUE INDEX IF NOT EXISTS requests_source_key_uidx ON requests (source_key)`,
		`CREATE INDEX IF NOT EXISTS requests_user_created_idx ON requests (user_id, created_at DESC, id DESC) WHERE deleted_at IS NULL`,
		`CREATE INDEX IF NOT EXISTS requests_status_created_idx ON requests (status, created_at DESC) WHERE deleted_at IS NULL`,
		`CREATE INDEX IF NOT EXISTS requests_created_idx ON requests (created_at DESC) WHERE deleted_at IS NULL`,
		`CREATE INDEX IF NOT EXISTS requests_assigned_status_idx ON requests (assigned_to, status, created_at DESC) WHERE deleted_at IS NULL`,

		`CREATE TABLE IF NOT EXISTS request_events (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			request_id BIGINT NOT NULL REFERENCES requests(id),
			actor_user_id BIGINT NOT NULL REFERENCES users(id),
			event_type TEXT NOT NULL,
			old_status TEXT,
			new_status TEXT,
			old_assignee_id BIGINT,
			new_assignee_id BIGINT,
			details TEXT NOT NULL DEFAULT '',
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		)`,
		`ALTER TABLE request_events ADD COLUMN IF NOT EXISTS old_assignee_id BIGINT`,
		`ALTER TABLE request_events ADD COLUMN IF NOT EXISTS new_assignee_id BIGINT`,
		`ALTER TABLE request_events ADD COLUMN IF NOT EXISTS details TEXT NOT NULL DEFAULT ''`,
		`CREATE INDEX IF NOT EXISTS request_events_request_created_idx ON request_events (request_id, created_at DESC, id DESC)`,
		`CREATE INDEX IF NOT EXISTS request_events_actor_created_idx ON request_events (actor_user_id, created_at DESC, id DESC)`,
		`CREATE INDEX IF NOT EXISTS request_events_status_created_idx ON request_events (event_type, new_status, created_at, request_id)`,

		`CREATE TABLE IF NOT EXISTS request_comments (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			request_id BIGINT NOT NULL REFERENCES requests(id),
			author_user_id BIGINT NOT NULL REFERENCES users(id),
			body TEXT NOT NULL,
			visibility TEXT NOT NULL DEFAULT 'internal',
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
			CONSTRAINT request_comments_visibility_check CHECK (visibility IN ('internal', 'student'))
		)`,
		`CREATE INDEX IF NOT EXISTS request_comments_request_created_idx ON request_comments (request_id, created_at, id)`,
		`CREATE TABLE IF NOT EXISTS telegram_notifications (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			telegram_id BIGINT NOT NULL,
			request_id BIGINT NOT NULL REFERENCES requests(id),
			body TEXT NOT NULL,
			status TEXT NOT NULL DEFAULT '',
			attempts INTEGER NOT NULL DEFAULT 0,
			available_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
			locked_until TIMESTAMPTZ,
			delivered_at TIMESTAMPTZ,
			last_error TEXT NOT NULL DEFAULT '',
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		)`,
		`ALTER TABLE telegram_notifications ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT ''`,
		`CREATE INDEX IF NOT EXISTS telegram_notifications_pending_idx ON telegram_notifications (available_at, id) WHERE delivered_at IS NULL`,

		`CREATE TABLE IF NOT EXISTS admin_auth_flows (
			state_hash BYTEA PRIMARY KEY,
			nonce TEXT NOT NULL,
			code_verifier TEXT NOT NULL,
			expires_at TIMESTAMPTZ NOT NULL,
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		)`,
		`CREATE INDEX IF NOT EXISTS admin_auth_flows_expires_idx ON admin_auth_flows (expires_at)`,
		`CREATE TABLE IF NOT EXISTS admin_sessions (
			token_hash BYTEA PRIMARY KEY,
			csrf_hash BYTEA NOT NULL,
			user_id BIGINT NOT NULL REFERENCES users(id),
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
			expires_at TIMESTAMPTZ NOT NULL,
			revoked_at TIMESTAMPTZ
		)`,
		`CREATE INDEX IF NOT EXISTS admin_sessions_user_idx ON admin_sessions (user_id, expires_at DESC)`,
		`CREATE TABLE IF NOT EXISTS user_admin_events (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			actor_user_id BIGINT NOT NULL REFERENCES users(id),
			target_user_id BIGINT NOT NULL REFERENCES users(id),
			event_type TEXT NOT NULL,
			old_value TEXT NOT NULL DEFAULT '',
			new_value TEXT NOT NULL DEFAULT '',
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		)`,
		`CREATE INDEX IF NOT EXISTS user_admin_events_target_idx ON user_admin_events (target_user_id, created_at DESC, id DESC)`,
	}

	for _, statement := range statements {
		if _, err := tx.ExecContext(ctx, statement); err != nil {
			return fmt.Errorf("execute schema statement: %w", err)
		}
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit schema transaction: %w", err)
	}
	return nil
}
